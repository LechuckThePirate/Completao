// masks: the quest's own or, if it has none, the one inherited from its mandatory prerequisites
// (intersection), so a quest that needs a Horde-only or class-only quest is Horde-only or class-only too
function inheritedMask(field) {
    const memo = new Map();
    const mask = (id, depth) => {
        if (memo.has(id)) return memo.get(id);
        memo.set(id, false); // cuts cycles
        const q = quests.get(id);
        if (!q) return false;
        let m = q[field] || null;
        if (m === ALL_RACES && field === 6) m = null;
        if (!m && depth < 30) {
            const parents = [...(q[12] ?? [])];
            if ((q[13] ?? []).length === 1) parents.push(q[13][0]);
            for (const p of parents) {
                const pm = mask(p, depth + 1);
                if (pm) m = m ? (m & pm) : pm;
            }
            if (m === 0) m = null;
        }
        memo.set(id, m || false);
        return memo.get(id);
    };
    return (id) => mask(id, 0) || null;
}
