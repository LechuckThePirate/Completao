// quest lines
// chain steps that share a name and races inside an entry are numbered in chain order: "Name (2/7)"
function displayNames(set) {
    const depth = new Map();
    const depthOf = (id) => {
        if (depth.has(id)) return depth.get(id);
        depth.set(id, 0);
        let m = 0;
        for (const p of pre(quests.get(id))) if (set.has(p)) m = Math.max(m, depthOf(p) + 1);
        depth.set(id, m);
        return m;
    };
    const groups = new Map();
    for (const id of set) {
        const q = quests.get(id);
        const key = `${q[1]}|${q[6]}`;
        if (!groups.has(key)) groups.set(key, []);
        groups.get(key).push(id);
    }
    const names = new Map();
    for (const g of groups.values()) {
        g.sort((a, b) => depthOf(a) - depthOf(b) || a - b);
        g.forEach((id, i) => names.set(id, g.length > 1 ? `${quests.get(id)[1]} (${i + 1}/${g.length})` : quests.get(id)[1]));
    }
    return names;
}

// exact factions -> faction; other race restrictions -> races; class restrictions -> classes (except in
// class entries, where they are the reason for being there)
function questLine(id, name, comment, noClasses) {
    const q = quests.get(id);
    const f = [`id = ${id}`, `name = ${lua(name)}`];
    if (q[5] > 0) f.push(`level = ${q[5]}`);
    if (q[4] > 0) f.push(`minLevel = ${q[4]}`);
    const grp = (q[12] ?? []).filter((p) => p > 0);
    let single = (q[13] ?? []).filter((p) => p > 0);
    if (single.length === 1) { grp.push(single[0]); single = []; }
    if (grp.length) f.push(`requires = { ${grp.join(", ")} }`);
    if (single.length > 1) f.push(`requiresAny = { ${single.join(", ")} }`);
    const races = raceMask(id);
    if (races === ALLIANCE) f.push('faction = "Alliance"');
    else if (races === HORDE) f.push('faction = "Horde"');
    else if (races) f.push(`races = ${races}`);
    const classes = classMask(id);
    if (classes && !noClasses) f.push(`classes = ${classes}`);
    if (dungeonOf.has(id)) f.push(`dungeon = ${lua(dungeonOf.get(id))}`);
    const giver = group(q[2], 1)[0], finisher = group(q[3], 1)[0];
    if (giver && npc(giver)) { f.push(`giver = ${lua(npc(giver)[1])}`); f.push(`start = ${location(giver)}`); }
    if (finisher && npc(finisher)) f.push(`finish = ${location(finisher)}`);
    const steps = stepsOf(q);
    if (steps.length) f.push(`steps = { ${steps.join(", ")} }`);
    const text = (q[8] ?? []).join(" ");
    if (text.trim()) f.push(`objective = ${lua(text)}`);
    return `    { ${f.join(", ")} },${comment ?? ""}`;
}

// rough level of an entry: 10th percentile of the required level and 90th of the quest level
function levelRange(set) {
    const req = [], lvl = [];
    for (const id of set) {
        const q = quests.get(id);
        if (q[4] > 0) req.push(q[4]);
        if (q[5] > 0) lvl.push(q[5]);
    }
    req.sort((a, b) => a - b); lvl.sort((a, b) => a - b);
    const lo = req[Math.max(1, Math.ceil(req.length * 0.1)) - 1] ?? 1;
    const hi = lvl[Math.max(1, Math.ceil(lvl.length * 0.9)) - 1] ?? lo;
    return [lo, Math.max(lo, hi)];
}

function emitEntry(out, entryId, header, set, noClasses, commentOf) {
    const sorted = [...set].sort((a, b) => a - b);
    const names = displayNames(set);
    if (header) out.push(header);
    out.push(`ns.AddQuests(${lua(entryId)}, {`);
    for (const id of sorted) out.push(questLine(id, names.get(id), commentOf?.(id), noClasses));
    out.push("})", "");
    return sorted.length;
}
