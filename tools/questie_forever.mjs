// locations and steps
// an NPC's location: preferred zone (its most common) and first coordinate; NPCs inside an instance have
// coordinates -1 and are emitted without a position
function location(npcId) {
    const n = npc(npcId);
    const parts = [`npc = ${lua(n[1])}`];
    const spawns = keyed(n[7]);
    if (Object.keys(spawns).length) {
        const zone = spawns[n[9]] ? n[9] : Math.min(...Object.keys(spawns).map(Number));
        const c = spawns[zone]?.[0];
        if (c && c[0] >= 0) parts.push(`area = ${zone}`, `x = ${f1(c[0])}`, `y = ${f1(c[1])}`);
    }
    return `{ ${parts.join(", ")} }`;
}

// the densest spot of a cloud of points: the 6x6 cell (with its neighbors) holding the most
function densest(pts) {
    const CELL = 6, grid = new Map(), cells = [];
    const cell = (v) => Math.floor(v / CELL);
    const key = (i, j) => i * 1000 + j;
    for (const [x, y] of pts) {
        const k = key(cell(x), cell(y));
        if (!grid.has(k)) { grid.set(k, 0); cells.push([cell(x), cell(y)]); }
        grid.set(k, grid.get(k) + 1);
    }
    let best, bestN = -1;
    for (const [i, j] of cells) {
        let n = 0;
        for (let di = -1; di <= 1; di++) for (let dj = -1; dj <= 1; dj++) n += grid.get(key(i + di, j + dj)) ?? 0;
        if (n > bestN) { best = [i, j]; bestN = n; }
    }
    const near = pts.filter(([x, y]) => Math.abs(cell(x) - best[0]) <= 1 && Math.abs(cell(y) - best[1]) <= 1);
    return [near.reduce((s, p) => s + p[0], 0) / near.length, near.reduce((s, p) => s + p[1], 0) / near.length];
}

function stepFrom(name, byZone) {
    if (!name) return null;
    let bestZone, bestPts;
    for (const [zone, pts] of Object.entries(byZone)) {
        if (!bestPts || pts.length > bestPts.length || (pts.length === bestPts.length && Number(zone) < Number(bestZone))) { bestZone = zone; bestPts = pts; }
    }
    if (!bestPts) return null;
    const valid = bestPts.filter((c) => c[0] >= 0);
    if (!valid.length) return `{ name = ${lua(name)}, area = ${areaOf.get(Number(bestZone)) ?? bestZone} }`; // inside an instance
    const [x, y] = densest(valid);
    return `{ name = ${lua(name)}, area = ${bestZone}, x = ${f1(x)}, y = ${f1(y)} }`;
}
const addSpawns = (acc, spawns) => { for (const [zone, list] of Object.entries(keyed(spawns))) (acc[zone] ??= []).push(...list); };

// one step per objective: kill, world object, collect an item (from its droppers), kill credit, event
function stepsOf(q) {
    const steps = [];
    const add = (s) => { if (s && steps.length < MAX_STEPS) steps.push(s); };
    const obj = q[10];
    for (const o of group(obj, 1)) { const n = npc(o[0]); if (n) { const acc = {}; addSpawns(acc, n[7]); add(stepFrom(o[1] || n[1], acc)); } }
    for (const o of group(obj, 2)) { const ob = object(o[0]); if (ob) { const acc = {}; addSpawns(acc, ob[4]); add(stepFrom(o[1] || ob[1], acc)); } }
    for (const o of group(obj, 3)) {
        const it = item(o[0]);
        if (!it) continue;
        const acc = {};
        let used = 0;
        for (const id of it[2] ?? []) if (used < MAX_SOURCES && npc(id)) { addSpawns(acc, npc(id)[7]); used++; }
        for (const id of it[3] ?? []) if (used < MAX_SOURCES && object(id)) { addSpawns(acc, object(id)[4]); used++; }
        add(stepFrom(it[1], acc));
    }
    for (const o of group(obj, 5)) { // kill credit: { {npcs}, base npc, text }
        const acc = {};
        for (const id of o[0] ?? []) if (npc(id)) addSpawns(acc, npc(id)[7]);
        add(stepFrom(o[2] || npc(o[1])?.[1], acc));
    }
    const trigger = q[9];
    if (Array.isArray(trigger) && trigger[1]) add(stepFrom(trigger[0], keyed(trigger[1])));
    return steps;
}

