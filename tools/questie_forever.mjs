// prerequisites: up to UP_HOPS steps back; continuations: DOWN_HOPS forward (further on, chains from other
// zones creep in, e.g. Argent Dawn from Stratholme); it never crosses into another instance's own quests
function collect(area) {
    const set = new Set(core.get(area) ?? []);
    const foreign = (id) => [...core].some(([d, ids]) => d !== area && ids.has(id));
    const walk = (neighbours, maxHops) => {
        let frontier = [...(core.get(area) ?? [])];
        for (let hop = 0; hop < maxHops; hop++) {
            const next = [];
            for (const id of frontier) {
                for (const n of neighbours(id)) {
                    if (quests.has(n) && !set.has(n) && !foreign(n)) { set.add(n); next.push(n); }
                }
            }
            if (!next.length) break;
            frontier = next;
        }
    };
    walk((id) => pre(quests.get(id)), UP_HOPS);
    walk((id) => children.get(id) ?? [], DOWN_HOPS);
    return set;
}

